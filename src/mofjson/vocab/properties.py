_BAND_GAP_PAREN_RE = re.compile(
    r"^Band gap\s*\((?P<func>[^)]+)\)\s*$",
    re.IGNORECASE,
)


def lookup_property_alias(raw_name: str) -> PropertyAlias | None:
    """Look up a raw property name in PROPERTY_ALIASES (exact then NormalizeKey)."""
    if raw_name in PROPERTY_ALIASES:
        return PROPERTY_ALIASES[raw_name]
    key = NormalizeKey(raw_name)
    if key in PROPERTY_ALIASES:
        return PROPERTY_ALIASES[key]
    # Dynamic band-gap (Functional) pattern for variants not enumerated
    m = _BAND_GAP_PAREN_RE.match(raw_name.strip())
    if m:
        return PropertyAlias(
            "band_gap",
            "energy",
            "eV",
            None,
            m.group("func").strip(),
            "property",
        )
    if NormalizeKey(raw_name).startswith("space group"):
        return PropertyAlias(None, "symmetry", None, None, None, "symmetry")
    if NormalizeKey(raw_name).startswith("crystal system"):
        return PropertyAlias(None, "symmetry", None, None, None, "symmetry")
    return None


